  await context.route('**/*', async route => {
    const url = new URL(route.request().url());
    if (url.hostname !== '127.0.0.1' || url.port !== qaPort || url.pathname.startsWith('/api')) {
      receipt.blockedRequests.push({ origin: url.origin, api: url.pathname.startsWith('/api') });
      return route.abort();
    }
    return route.continue();
  });
  const page = await context.newPage();
  page.on('pageerror', error => receipt.errors.push(error.message));
  await page.goto(`http://127.0.0.1:${qaPort}/.omo/evidence/canvas-library/play.html`);
  const canvas = page.getByRole('application');
