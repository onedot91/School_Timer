  await page.getByRole('textbox', { name: '글쓴이', exact: true }).fill('김별');
  await page.getByRole('textbox', { name: '쪽수', exact: true }).fill('0');
  await page.getByRole('button', { name: '책 받기', exact: true }).click();
  assert.match(await page.getByRole('alert').innerText(), /1~5000/);
  assert.deepEqual(await position(), frozen);
  receipt.checks.invalidAndModalFreeze = true;
  await shot('invalid');
  await page.getByRole('textbox', { name: '쪽수', exact: true }).fill('80');
  await page.getByRole('button', { name: '책 받기', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await canvas.evaluate(el => document.activeElement === el), true);
  await shot('carry');
  await walkAxis('x', 266);
  await walkAxis('y', 122);
  await page.keyboard.press('e');
  await page.getByRole('button', { name: '빈자리 1', exact: true }).waitFor();
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '빈자리 1');
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.getByRole('button', { name: '빈자리 7', exact: true }).evaluate(el => document.activeElement === el), true, 'ArrowDown must focus slot7');
  for (let n = 0; n < 8; n++) {
    await page.keyboard.press('Tab');
    assert.equal(await page.getByRole('dialog').evaluate(el => el.contains(document.activeElement)), true, `Tab ${n} escaped slot dialog`);
  }
  receipt.checks.slotKeyboardAndFocusTrap = true;
  await shot('slots');
  await page.keyboard.press('Escape');
  await page.keyboard.press('e');
  await page.getByRole('button', { name: '빈자리 1', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await shot('placement-start');
  await page.waitForTimeout(100);
  await shot('placement-mid');
  await page.waitForTimeout(500);
  await shot('placed');
  await walkAxis('x', 200);
  await page.keyboard.press('e');
  assert.match(await page.getByRole('dialog').innerText(), /달빛 우체국/);
  assert.match(await page.getByRole('dialog').innerText(), /김별/);
  await shot('details');
  await page.keyboard.press('Escape');
  receipt.checks.actualBookLoop = true;
